def _settings(args: argparse.Namespace) -> Settings:
    path = getattr(args, "config", None) or default_config_path()
    return load_settings(path)


@contextmanager
def _journal(settings: Settings) -> Iterator[Journal]:
    journal = Journal(settings.database_path()).initialize()
    try:
        yield journal
    finally:
        journal.close()


def _ledger(settings: Settings, journal: Journal) -> AllocationLedger:
    ledger = AllocationLedger(journal, settings.allocation.ceiling_usd)
    ledger.rebuild()
    return ledger


def _parse_params(pairs: Sequence[str] | None) -> dict[str, object]:
    out: dict[str, object] = {}
    for pair in pairs or ():
        if "=" not in pair:
            raise CryptobotError(f"--param expects key=value, got {pair!r}")
        key, raw = pair.split("=", 1)
        out[key.strip()] = _coerce(raw.strip())
    return out


def _coerce(raw: str) -> object:
    try:
        return int(raw)
    except ValueError:
        pass
    try:
        return Decimal(raw)
    except Exception:  # noqa: BLE001
        return raw


def _parse_grid(pairs: Sequence[str] | None) -> dict[str, list[object]]:
    grid: dict[str, list[object]] = {}
    for pair in pairs or ():
        if "=" not in pair:
            raise CryptobotError(f"--grid expects key=v1,v2,..., got {pair!r}")
        key, raw = pair.split("=", 1)
        grid[key.strip()] = [_coerce(item.strip()) for item in raw.split(",") if item.strip()]
    return grid


def _merge_params(settings: Settings, overrides: Mapping[str, object]) -> dict[str, object]:
    merged: dict[str, object] = dict(settings.strategy.params)
    merged.update(overrides)
    return merged


def _cost_model(args: argparse.Namespace) -> CostModel:
    return CostModel(
        fee_bps=Decimal(str(getattr(args, "fee_bps", 25))),
        slippage_bps=Decimal(str(getattr(args, "slippage_bps", 25))),
    )


def _dataset(args: argparse.Namespace, settings: Settings) -> BarDataset:
    if getattr(args, "data", None):
        return BarDataset.from_file(args.data)
    if getattr(args, "from_journal", False):
        with _journal(settings) as journal:
            return BarDataset.from_journal(
                journal,
                settings.market.symbols[0],
                settings.market.timeframe,
                limit=getattr(args, "bars", 600),
            )
    readme = "synthetic dataset (seed=%s, bars=%s)" % (
        getattr(args, "seed", 7),
        getattr(args, "bars", 600),
    )
    dataset = BarDataset(
        settings.market.symbols[0],
        settings.market.timeframe,
        tuple(
            synthetic_bars(
                symbol=settings.market.symbols[0],
                timeframe=settings.market.timeframe,
                count=int(getattr(args, "bars", 600)),
                seed=int(getattr(args, "seed", 7)),
            )
        ),
    )
    print(SYNTHETIC_WARNING)
    print(f"  {readme}")
    print()
    return dataset


def _backtest_config(args: argparse.Namespace, settings: Settings) -> BacktestConfig:
    ceiling = getattr(args, "ceiling", None) or settings.allocation.ceiling_usd
    return BacktestConfig(
        ceiling=Decimal(str(ceiling)),
        max_position_pct=settings.risk.max_position_pct,
        per_trade_risk_pct=settings.risk.per_trade_risk_pct,
        costs=_cost_model(args),
    )


