def cmd_backtest(args: argparse.Namespace) -> int:
    settings = _settings(args)
    dataset = _dataset(args, settings)
    cls = strategy_class(args.strategy)
    params = _merge_params(settings, _parse_params(args.param))
    strategy = cls(params)
    if len(dataset) <= strategy.min_bars:
        print(f"dataset too short: {len(dataset)} bars, needs > {strategy.min_bars}",
              file=sys.stderr)
        return REFUSED
    if args.lookahead_check:
        violations = verify_no_lookahead(strategy, dataset.bars)
        print(f"look-ahead check: {'PASS' if not violations else 'FAIL'}")
        for violation in violations:
            print(f"  {violation}")
        if violations:
            return FAILED
    result = run_backtest(strategy, dataset, _backtest_config(args, settings))
    print(result.summary())
    return OK


def cmd_research(args: argparse.Namespace) -> int:
    settings = _settings(args)
    dataset = _dataset(args, settings)
    cls = strategy_class(args.strategy)
    grid = _parse_grid(args.grid)
    if not grid:
        print("refusing to run a suite with no --grid; nothing would be learned",
              file=sys.stderr)
        return REFUSED
    with _journal(settings) as journal:
        suite = run_suite(
            args.name or "cli-suite",
            cls,
            dataset,
            grid,
            config=_backtest_config(args, settings),
            train_fraction=float(args.train_fraction),
            journal=journal,
            min_trades=int(args.min_trades),
        )
    print(suite.summary())
    return OK


def cmd_walk_forward(args: argparse.Namespace) -> int:
    settings = _settings(args)
    dataset = _dataset(args, settings)
    cls = strategy_class(args.strategy)
    config = _backtest_config(args, settings)
    grid = _parse_grid(getattr(args, "grid", None))
    if grid:
        folds = walk_forward_optimised(
            cls,
            grid,
            dataset,
            train_bars=int(args.train_bars),
            test_bars=int(args.test_bars),
            config=config,
        )
        print(render_walk_forward_optimised(folds))
        return OK
    params = _merge_params(settings, _parse_params(args.param))
    folds = walk_forward(
        cls,
        params,
        dataset,
        train_bars=int(args.train_bars),
        test_bars=int(args.test_bars),
        config=config,
    )
    print("rolling out-of-sample evaluation (parameters fixed) - pass --grid to re-select")
    print(render_walk_forward(folds))
    return OK


def cmd_sensitivity(args: argparse.Namespace) -> int:
    settings = _settings(args)
    dataset = _dataset(args, settings)
    cls = strategy_class(args.strategy)
    base = _merge_params(settings, _parse_params(args.param))

    def factory(overrides: Mapping[str, object] | None = None):
        return cls({**base, **(overrides or {})})

    grid = _parse_grid(args.grid)
    if not grid:
        print("refusing to sweep with no --grid", file=sys.stderr)
        return REFUSED
    results = parameter_sensitivity(
        factory, dataset, grid, config=_backtest_config(args, settings)
    )
    print(summarise_sensitivity(results))
    return OK


def cmd_challengers(args: argparse.Namespace) -> int:
    settings = _settings(args)
    dataset = _dataset(args, settings)
    cls = strategy_class(args.strategy)
    grid = _parse_grid(args.grid)
    if not grid:
        print(
            "refusing to run challengers with no --grid; there is nothing to compare",
            file=sys.stderr,
        )
        return REFUSED
    baseline = _merge_params(settings, _parse_params(args.baseline))
    rule = PromotionRule(
        min_out_of_sample_trades=int(args.min_oos_trades),
        min_improvement_pct=Decimal(str(args.min_improvement_pct)),
        max_drawdown_slack_pct=Decimal(str(args.drawdown_slack)),
    )
    report = run_challengers(
        cls,
        dataset,
        baseline=baseline,
        grid=grid,
        config=_backtest_config(args, settings),
        train_fraction=float(args.train_fraction),
        rule=rule,
    )
    if args.json:
        print(
            json.dumps(
                {
                    "baseline": dict(report.baseline_params),
                    "baseline_out_of_sample_pct": str(
                        report.baseline_out_of_sample.total_return_pct
                    ),
                    "promoted": [verdict.as_dict() for verdict in report.promotable],
                    "verdicts": [verdict.as_dict() for verdict in report.verdicts],
                    "caveats": list(report.caveats),
                },
                indent=2,
            )
        )
    else:
        print(report.summary())
    return OK


