def cmd_data_refresh(args: argparse.Namespace) -> int:
    settings = _settings(args)
    missing = settings.alpaca.missing_credential_names()
    if missing:
        print(
            "refusing to fetch: missing credentials -> " + ", ".join(missing),
            file=sys.stderr,
        )
        print(
            "  set them in your environment (see .env.example); never paste them here",
            file=sys.stderr,
        )
        return REFUSED
    client = build_data_client(settings)
    with Runtime.build(settings, mode=BrokerMode.SIMULATED, data_client=client) as runtime:
        symbols = [args.symbol] if args.symbol else list(settings.market.symbols)
        failures = 0
        for symbol in symbols:
            try:
                result = runtime.data.refresh(symbol, lookback_bars=args.lookback)
                print(result.summary())
                for expected, found in result.report.gaps[:10]:
                    print(f"  gap: expected {expected.isoformat()}, found {found.isoformat()}")
                if result.report.rejected:
                    print(f"  rejected {len(result.report.rejected)} malformed bar(s)")
            except Exception as exc:  # noqa: BLE001
                failures += 1
                print(f"{symbol}: refresh failed: {exc}", file=sys.stderr)
    return OK if failures == 0 else FAILED


