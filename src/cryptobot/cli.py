"""Command line interface.

Two rules shape this file:

1. **Reading is free, changing state is explicit.** ``status``, ``ledger``,
   ``backtest`` and friends never place an order. Commands that do - ``run-once
   --submit``, ``paper-run --submit``, ``cancel-all`` - say so in their help text
   and print a banner before doing anything.
2. **No secrets in output.** Configuration dumps name the environment variables
   that must be set; they never print their values.

Exit codes: ``0`` success, ``1`` the operation reported a failure, ``2`` the
operation was refused or errored, ``130`` interrupted.
"""

