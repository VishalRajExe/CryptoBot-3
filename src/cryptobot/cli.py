def _print_cycle(result) -> None:
    print(f"  {result.summary()}")
    for reason in result.blocked_reasons:
        print(f"      blocked: {reason}")
    if result.intent is not None:
        print(
            f"      intent: {result.intent.side.value} {result.intent.quantity} "
            f"{result.intent.symbol} notional={result.intent.notional:.2f} "
            f"coid={result.intent.client_order_id}"
        )


def cmd_run_once(args: argparse.Namespace) -> int:
    settings = _settings(args)
    mode = BrokerMode.parse(args.mode)
    submit = bool(args.submit)
    if mode is BrokerMode.PAPER:
        print(PAPER_BANNER)
    with Runtime.build(settings, mode=mode) as runtime:
        preflight = runtime.preflight()
        _print_preflight(preflight)
        if not preflight.ok:
            return FAILED
        runtime.sync_prices()
        print()
        print(f"evaluating {', '.join(settings.market.symbols)} "
              f"(strategy={runtime.strategy.name} {runtime.strategy.version}, "
              f"submit={'yes' if submit else 'no'})")
        for result in runtime.engine.evaluate_all(submit=submit):
            _print_cycle(result)
        runtime.capture_account()
        report = runtime.reconcile(context="run-once")
        print()
        print(report.summary())
        return OK


def cmd_paper_run(args: argparse.Namespace) -> int:
    settings = _settings(args)
    print(PAPER_BANNER)
    print()
    if args.submit:
        print("*** --submit given: approved intents WILL be sent to the paper account ***")
    else:
        print("dry run: risk decisions are made, nothing is sent (pass --submit to trade)")
    print()
    with Runtime.build(settings, mode=BrokerMode.PAPER) as runtime:
        loop = TradingLoop(
            runtime,
            submit=bool(args.submit),
            interval_seconds=float(args.interval),
            reconcile_every=int(args.reconcile_every),
            on_cycle=_print_cycle,
        )
        print(f"interval={args.interval}s reconcile_every={args.reconcile_every} "
              f"iterations={args.iterations or 'unbounded'} (Ctrl+C to stop)")
        try:
            report = loop.run(iterations=args.iterations)
        except KeyboardInterrupt:
            print("\ninterrupted")
            return INTERRUPTED
        print()
        print(report.summary())
        for error in report.errors:
            print(f"  error: {error}")
        return OK if not report.errors else FAILED


