def cmd_ai_review(args: argparse.Namespace) -> int:
    settings = _settings(args)
    with _journal(settings) as journal:
        bars = journal.recent_bars(
            settings.market.symbols[0], settings.market.timeframe, settings.market.lookback_bars
        )
        if not bars:
            print("no cached bars; run `cryptobot seed-demo` or `data-refresh` first",
                  file=sys.stderr)
            return REFUSED
        if not args.enable:
            print("shadow AI is disabled. Nothing was sent to any model.")
            print("  re-run with --enable --provider static to exercise the record path")
            return OK
        provider = StaticProvider(args.payload) if args.provider == "static" else None
        if provider is None:
            print(f"unknown provider {args.provider!r}", file=sys.stderr)
            return REFUSED
        analyst = ShadowAnalyst(
            journal,
            provider,
            enabled=True,
            max_latency_ms=int(args.max_latency_ms),
            max_cost_usd=Decimal(str(args.max_cost_usd)),
        )
        assessment = analyst.assess(build_context_from_bars(bars))
        if assessment is None:
            print(f"no assessment recorded (shadow only): {analyst.last_error}")
            return FAILED
        print("SHADOW ASSESSMENT (recorded; cannot influence orders)")
        print(f"  {assessment.summary()}")
        print(f"  prompt_hash {assessment.prompt_hash}")
        print(f"  rationale   {assessment.rationale}")
        for risk in assessment.key_risks:
            print(f"  risk        {risk}")
    return OK


