def _set_state(args: argparse.Namespace, state: SystemState, verb: str) -> int:
    settings = _settings(args)
    reason = args.reason
    if not reason:
        print(f"refusing to {verb}: --reason is required", file=sys.stderr)
        return REFUSED
    with _journal(settings) as journal:
        previous, _, _ = journal.get_system_state()
        journal.set_system_state(state, reason)
        journal.record_reconciliation(
            "operator_state_change",
            "warning" if state is not SystemState.ACTIVE else "info",
            {
                "from": previous.value,
                "to": state.value,
                "reason": reason,
                "actor": "cli",
            },
        )
        print(f"system state: {previous.value} -> {state.value}")
        print(f"  reason: {reason}")
        if state is SystemState.PAUSE_ENTRIES:
            print("  new entries are blocked; open positions and orders are untouched")
        if state is SystemState.KILLED:
            print("  entries blocked; cancelling open orders is still permitted")
    return OK


def cmd_pause(args: argparse.Namespace) -> int:
    return _set_state(args, SystemState.PAUSE_ENTRIES, "pause")


def cmd_resume(args: argparse.Namespace) -> int:
    return _set_state(args, SystemState.ACTIVE, "resume")


def cmd_kill(args: argparse.Namespace) -> int:
    return _set_state(args, SystemState.KILLED, "engage the kill switch")


def cmd_cancel_all(args: argparse.Namespace) -> int:
    settings = _settings(args)
    mode = BrokerMode.parse(args.mode)
    with Journal(settings.database_path()).initialize() as journal:
        state, reason, _ = journal.get_system_state()
        if state is SystemState.HALTED:
            print(
                f"refusing to cancel: system is HALTED ({reason}); investigate first",
                file=sys.stderr,
            )
            return REFUSED
    with Runtime.build(settings, mode=mode) as runtime:
        open_orders = [
            record for record in runtime.journal.list_orders(
                [s for s in OrderStatus if s.is_open], limit=100
            )
        ]
        if not open_orders:
            print("no open orders")
            return OK
        for record in open_orders:
            print(f"  {record.client_order_id}  {record.symbol} {record.side.value} "
                  f"{record.quantity}  {record.status.value}")
        if not args.yes:
            print("refusing to cancel without --yes", file=sys.stderr)
            return REFUSED
        failures = 0
        for record in open_orders:
            try:
                cancelled = runtime.adapter.cancel(record.client_order_id)
                print(f"  cancel {record.client_order_id}: "
                      f"{'ok' if cancelled else 'broker refused'}")
            except Exception as exc:  # noqa: BLE001
                failures += 1
                print(f"  cancel {record.client_order_id}: {exc}", file=sys.stderr)
        runtime.reconcile(context="cancel-all")
        return OK if failures == 0 else FAILED


