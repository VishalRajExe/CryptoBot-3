def _print_preflight(report) -> None:
    """Print the verdict *and* the reasons: a bare "FAILED" is not actionable."""
    print(report.summary())
    for check in report.failures:
        print(f"  FAILED  {check.name}: {check.detail}")
    for check in report.warnings:
        print(f"  warning {check.name}: {check.detail}")


def cmd_preflight(args: argparse.Namespace) -> int:
    settings = _settings(args)
    mode = BrokerMode.parse(getattr(args, "mode", "simulated"))
    with Runtime.build(settings, mode=mode) as runtime:
        report = runtime.preflight()
        _print_preflight(report)
        return OK if report.ok else FAILED


def cmd_experiments(args: argparse.Namespace) -> int:
    settings = _settings(args)
    with _journal(settings) as journal:
        rows = journal.list_experiments(limit=args.limit)
        if not rows:
            print("(no experiments recorded)")
            return OK
        for row in rows:
            metrics = json.loads(row["metrics_json"] or "{}")
            print(
                f"{row['created_at'][:19]}  {row['name']:<28} {row['strategy']:<22} "
                f"test={metrics.get('test_total_return_pct', 'n/a'):>8}%  "
                f"{row['strategy_version']}"
            )
    return OK


